#!/usr/bin/env python3
"""Generate src/hooks_gen.cpp: every override of a recompiled function that
the project installs (PROBES.md). Replaces tools/gen_d3d_observe.py.

Two sources, merged so each address gets exactly one strong override (a
second one would be a duplicate symbol):
- the D3D observer: every function in [LO, HI) called from outside that
  range (from the generated call graph) is counted per frame when
  gears1_d3d_observe is set; Swap (8223E860) writes the per-frame line.
- tools/hook_table.py: probe hooks (passes, policies, draws, events) that
  call into src/probes.cpp, plus extra pre hooks (shader dump, depth bias).

Each override bumps its counter, runs its pre hooks and probe, then calls
`__imp__sub_XXXXXXXX` (the original).

Usage: tools/gen_hooks.py [LO HI]   (hex, default 821F8000 82280000)
"""
import collections, glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from hook_table import PROBES  # noqa: E402

GEN = os.path.join(ROOT, 'generated', 'default')
LO = int(sys.argv[1], 16) if len(sys.argv) > 2 else 0x821F8000
HI = int(sys.argv[2], 16) if len(sys.argv) > 2 else 0x82280000
SWAP = 0x8223E860  # calls VdSwap: one call per presented frame
KINDS = {'count': 'kCount', 'pass': 'kPass', 'scope': 'kScope', 'policy': 'kPolicy',
         'draw': 'kDraw', 'event': 'kEvent', 'frame': 'kFrame'}

fre = re.compile(r'^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\)')
cre = re.compile(r'\bsub_([0-9A-F]{8})\(ctx, base\)')
callers = collections.defaultdict(set)
funcs = set()
for path in glob.glob(os.path.join(GEN, '*_recomp.*.cpp')):
    cur = None
    for line in open(path):
        m = fre.match(line)
        if m:
            cur = int(m.group(1), 16)
            funcs.add(cur)
            continue
        if cur is not None:
            for c in cre.findall(line):
                c = int(c, 16)
                if c != cur:
                    callers[c].add(cur)
if not funcs:
    sys.exit(f'no recompiled functions found under {GEN}')

inside = lambda a: LO <= a < HI
observed = sorted(a for a in funcs if inside(a) and any(not inside(c) for c in callers[a]))
if SWAP not in observed:
    observed.append(SWAP)
count_index = {a: i for i, a in enumerate(observed)}

probes = {}
for i, (address, name, kind, extra) in enumerate(PROBES):
    if kind not in KINDS:
        sys.exit(f'{name}: unknown kind {kind}')
    if address not in funcs:
        sys.exit(f'{name}: sub_{address:08X} is not a recompiled function')
    if address in probes:
        sys.exit(f'{name}: sub_{address:08X} listed twice')
    probes[address] = (i, name, kind, extra)

pre_hooks = sorted({f for _, _, _, extra in PROBES for f in extra.get('pre', [])})
post_hooks = sorted({f for _, _, _, extra in PROBES for f in extra.get('post', [])})

out = [
    '// GENERATED by tools/gen_hooks.py from tools/hook_table.py - do not edit.',
    '// Overrides of recompiled functions: D3D call counts (gears1_d3d_observe)',
    '// and probe hooks (PROBES.md, src/probes.cpp).',
    '',
    '#include <atomic>',
    '#include <cstdint>',
    '#include <cstdio>',
    '#include <string>',
    '',
    '#include <rex/cvar.h>',
    '#include <rex/ppc.h>',
    '',
    '#include "probes.h"',
    '',
    'REXCVAR_DEFINE_BOOL(gears1_d3d_observe, false, "Gears1",',
    '                    "Count calls to Xbox D3D library functions and log one line per frame");',
    'REXCVAR_DEFINE_STRING(gears1_d3d_observe_file, "d3d_observe.log", "Gears1",',
    '                      "Output file for gears1_d3d_observe");',
    '',
    f'const uint32_t kGears1ProbeCount = {len(PROBES)};',
    'const Gears1ProbeInfo kGears1Probes[] = {',
]
for address, name, kind, _ in PROBES:
    out.append(f'    {{0x{address:08X}, "{name}", Gears1ProbeKind::{KINDS[kind]}}},')
out += [
    '};',
    '',
    'namespace {',
    f'constexpr uint32_t kCount = {len(observed)};',
    'constexpr uint32_t kAddress[kCount] = {',
]
for i in range(0, len(observed), 6):
    out.append('    ' + ', '.join(f'0x{a:08X}' for a in observed[i:i + 6]) + ',')
out += [
    '};',
    'std::atomic<uint32_t> g_calls[kCount];',
    'uint64_t g_frame = 0;',
    '',
    'inline void Count(uint32_t index) {',
    '  if (REXCVAR_GET(gears1_d3d_observe)) g_calls[index].fetch_add(1, std::memory_order_relaxed);',
    '}',
    '',
    'void DumpFrame() {',
    '  static FILE* file = nullptr;',
    '  if (!file) {',
    '    file = std::fopen(std::string(REXCVAR_GET(gears1_d3d_observe_file)).c_str(), "w");',
    '    if (!file) return;',
    '  }',
    '  std::fprintf(file, "frame %llu", static_cast<unsigned long long>(g_frame++));',
    '  for (uint32_t i = 0; i < kCount; ++i) {',
    '    uint32_t n = g_calls[i].exchange(0, std::memory_order_relaxed);',
    '    if (n) std::fprintf(file, " %08X:%u", kAddress[i], n);',
    '  }',
    "  std::fputc('\\n', file);",
    '  std::fflush(file);',
    '}',
    '}  // namespace',
    '',
]
for f in pre_hooks:
    out.append(f'void {f}(PPCContext& ctx, uint8_t* base);')
for f in post_hooks:
    out.append(f'void {f}(const Gears1HookEntry& entry, PPCContext& ctx, uint8_t* base);')
out += [
    '',
    '#define OBSERVE(index, name)                                              \\',
    '  extern "C" void __imp__##name(PPCContext& __restrict, uint8_t*);         \\',
    '  extern "C" REX_FUNC(name) {                                             \\',
    '    Count(index);                                                         \\',
    '    __imp__##name(ctx, base);                                             \\',
    '  }',
    '',
]

for address in sorted(set(observed) | set(probes)):
    sym = f'sub_{address:08X}'
    probe = probes.get(address)
    if probe is None and address != SWAP:
        out.append(f'OBSERVE({count_index[address]}, {sym})')
        continue
    body = []
    if address in count_index:
        body.append(f'  Count({count_index[address]});')
    after = []
    if probe is not None:
        pid, name, kind, extra = probe
        body.append(f'  // {name}')
        body += [f'  {f}(ctx, base);' for f in extra.get('pre', [])]
        if extra.get('post'):
            body.append('  const Gears1HookEntry entry{ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, ctx.f1.f64};')
            after += [f'  {f}(entry, ctx, base);' for f in extra['post']]
        if kind in ('pass', 'scope'):
            body.append(f'  if (Gears1ProbeEnter({pid}, ctx, base)) {{')
            body.append('    ctx.r3.u64 = 0;')
            body.append('    return;')
            body.append('  }')
            after.append(f'  Gears1ProbeLeave({pid});')
        elif kind == 'policy':
            body.append(f'  Gears1ProbePolicy({pid});')
        elif kind == 'draw':
            body.append(f'  Gears1ProbeDraw({pid}, ctx, base);')
        elif kind == 'event':
            body.append(f'  Gears1ProbeEvent({pid}, ctx, base);')
        elif kind == 'frame':
            after.append('  Gears1ProbeFrameEnd(base);')
    if address == SWAP:
        body.append('  const bool observe = REXCVAR_GET(gears1_d3d_observe);')
        after.append('  if (observe) DumpFrame();')
    out += [f'extern "C" void __imp__{sym}(PPCContext& __restrict, uint8_t*);',
            f'extern "C" REX_FUNC({sym}) {{', *body, f'  __imp__{sym}(ctx, base);', *after, '}']

path = os.path.join(ROOT, 'src', 'hooks_gen.cpp')
open(path, 'w').write('\n'.join(out) + '\n')
print(f'{len(observed)} observed D3D functions, {len(PROBES)} probes -> {path}')
