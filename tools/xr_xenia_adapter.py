#!/usr/bin/env python3
"""Wrap a XenosRecomp vertex shader (HLSL) in ReXGlue/Xenia's VS interface so
its SPIR-V (compiled with DXC) can replace the emulator's translation of the
same shader in a GFXR capture (gfxrecon-replay --replace-shaders).

Translator prototype A of NATIVE_RENDERER.md. Prototype only: the vertex
fetch layout is passed in explicitly (from rexgpu-shader-tool's microcode
disassembly), and only what the skinning depth VS (VS 664) needs is handled:
float constants (no bool/loop constants), vertex fetch constant vf0, no
textures, position-only output.

Usage: tools/xr_xenia_adapter.py <xenosrecomp.hlsl> <out.hlsl> <fetch spec>...
fetch spec: <input name>:<dword offset>:<format>   format: f32x<N>, u8x4 (integer),
            un8x4 (normalised); all through vf0 with --stride dwords (default 10).
"""
import argparse, re

ap = argparse.ArgumentParser()
ap.add_argument('src')
ap.add_argument('dst')
ap.add_argument('fetch', nargs='+')
ap.add_argument('--stride', type=int, default=10)
# Vertex fetch constant index as the translator parses it (storage_index).
# The microcode disassembly prints `vf0` for D3D stream 0, which is fetch
# constant 95 (streams are numbered down from the top): sh664 reads
# fetch_constants[47].zw.
ap.add_argument('--vfetch-constant', type=int, default=95)
args = ap.parse_args()
src = open(args.src).read()

# Body of main(): everything between the parameter list's ')' + '{' and the
# function's closing brace.
m = re.search(r'void main\((.*?)\)\s*\{(.*)\}\s*$', src, re.S)
params, body = m.group(1), m.group(2)
inputs = {name: type_ for type_, name in re.findall(r'in\s+(\w+)\s+(\w+)\s*:', params)}

# Constant accessors: XenosRecomp's SPIR-V macros read from push-constant
# pointers; read the Xenia float constant buffer instead (same bounds clamp).
consts = []
for name, base, bound in re.findall(
        r'#define (\w+)\(INDEX\) select\(\(INDEX\) < (?:\d+), vk::RawBufferLoad<float4>\(g_PushConstants\.VertexShaderConstants \+ \((\d+) \+ min\(INDEX, (\d+)\)\) \* 16, 0x10\), 0\.0\)',
        src):
    consts.append(f'#define {name}(INDEX) select((INDEX) < {int(bound) + 1}, '
                  f'xe_c[{base} + min(INDEX, {bound})], 0.0)')
for name, offset in re.findall(
        r'#define (\w+) vk::RawBufferLoad<float4>\(g_PushConstants\.VertexShaderConstants \+ (\d+), 0x10\)', src):
    consts.append(f'#define {name} xe_c[{int(offset) // 16}]')

body = body.replace('oPos.xy += g_HalfPixelOffset * oPos.w;', '')
body = re.sub(r'tfetchTexcoord\(g_SwappedTexcoords, (\w+), \d+\)', r'\1', body)
body = re.sub(r'^\s*return;\s*$', '', body, flags=re.M)
# Xenia emits dp2/3/4 as a left-to-right sum of NoContraction products (not
# OpDot, whose order is up to the driver). Depth must match the base-pass
# shaders bit for bit (EQUAL depth test), so use the same order.
body = re.sub(r'\bdot\(', 'xe_dot(', body)
# Xenia marks every ALU result NoContraction; `precise` does the same in DXC.
body = re.sub(r'^(\s*)(float4 r\d+ = 0\.0;)', r'\1precise \2', body, flags=re.M)

fetch_lines = []
for spec in args.fetch:
    name, offset, fmt = spec.split(':')
    offset = int(offset)
    if fmt.startswith('f32x'):
        n = int(fmt[4:])
        words = ', '.join(f'XeLoadVertexWord(element, {offset + i}, endian)' for i in range(n))
        value = f'asfloat(uint{n}({words}))' if n > 1 else f'asfloat({words})'
        pad = {1: ', 0.0, 0.0, 1.0', 2: ', 0.0, 1.0', 3: ', 1.0', 4: ''}[n]
        value = f'float4({value}{pad})'
    elif fmt in ('u8x4', 'un8x4'):
        word = f'XeLoadVertexWord(element, {offset}, endian)'
        value = f'uint4({word} & 0xFF, ({word} >> 8) & 0xFF, ({word} >> 16) & 0xFF, {word} >> 24)'
        if fmt == 'un8x4':
            value = f'float4({value}) * (1.0f / 255.0f)'
    else:
        raise SystemExit(f'unknown format {fmt}')
    fetch_lines.append(f'\t{inputs[name]} {name} = {value};')

fc_word = args.vfetch_constant * 2
fc_vec, fc_w0, fc_w1 = fc_word >> 2, 'xyzw'[fc_word & 3], 'xyzw'[(fc_word & 3) + 1]
out = f'''// GENERATED by tools/xr_xenia_adapter.py from {args.src}
// XenosRecomp body + ReXGlue/Xenia vertex shader interface.

// Xenia descriptor layout (SpirvShaderTranslator): set 0 = shared memory,
// set 1 = system (0), float (1), bool/loop (3) and fetch (4) constants.
[[vk::binding(0, 1)]] cbuffer XeSystemConstants {{
\tuint4 xe_sys[31];   // offsets per SpirvShaderTranslator::SystemConstants
\tuint2 xe_sys_tail;  // +496 vertex_index_min, +500 vertex_index_max
}};
[[vk::binding(1, 1)]] cbuffer XeFloatConstants {{ float4 xe_c[256]; }};
[[vk::binding(4, 1)]] cbuffer XeFetchConstants {{ uint4 xe_fetch[48]; }};
[[vk::binding(0, 0)]] ByteAddressBuffer xe_shared_memory;

uint XeEndianSwap32(uint v, uint endian) {{
\t// 1 = 8in16, 2 = 8in32, 3 = 16in32.
\tif (endian == 1 || endian == 2) v = ((v & 0x00FF00FFu) << 8) | ((v >> 8) & 0x00FF00FFu);
\tif (endian == 2 || endian == 3) v = (v << 16) | (v >> 16);
\treturn v;
}}

float xe_dot(float2 a, float2 b) {{ precise float r = a.x * b.x; r = r + a.y * b.y; return r; }}
float xe_dot(float3 a, float3 b) {{ precise float r = a.x * b.x; r = r + a.y * b.y; r = r + a.z * b.z; return r; }}
float xe_dot(float4 a, float4 b) {{
\tprecise float r = a.x * b.x;
\tr = r + a.y * b.y;
\tr = r + a.z * b.z;
\tr = r + a.w * b.w;
\treturn r;
}}

uint XeLoadVertexWord(int element, int word, uint endian) {{
\treturn XeEndianSwap32(xe_shared_memory.Load(uint(element + word) * 4), endian);
}}

{chr(10).join(consts)}

float4 main(uint xe_vertex_index : SV_VertexID) : SV_Position
{{
\t// Vertex index as in SpirvShaderTranslator::StartVertexOrTessEvalShaderInMain
\t// (full 32-bit host indices, no indirect index load).
\tuint index = XeEndianSwap32(xe_vertex_index, xe_sys[0].z);
\tindex = (index + xe_sys[1].x) & 0xFFFFFFu;
\tindex = clamp(index, xe_sys_tail.x, xe_sys_tail.y);
\t// vfetch_full (fetch constant {args.vfetch_constant}): base address in dwords (fetch word 0 bits 2:31),
\t// index * stride, endianness from fetch word 1 bits 0:1.
\tint element = int(xe_fetch[{fc_vec}].{fc_w0} >> 2) + int(floor(float(index))) * {args.stride};
\tuint endian = xe_fetch[{fc_vec}].{fc_w1} & 3u;
{chr(10).join(fetch_lines)}
\tprecise float4 oPos = 0.0;
{body}
\t// Epilogue as in CompleteVertexOrTessEvalShaderInMain: undo 1/W, XY/W and
\t// Z/W per the system flags, then the guest-to-host NDC transform.
\tuint flags = xe_sys[0].x;
\tprecise float w = (flags & (1u << 10)) ? oPos.w : 1.0f / oPos.w;
\tprecise float2 xy = (flags & (1u << 8)) ? oPos.xy * w : oPos.xy;
\tprecise float z = (flags & (1u << 9)) ? oPos.z * w : oPos.z;
\tfloat3 ndc_scale = asfloat(uint3(xe_sys[7].w, xe_sys[8].x, xe_sys[8].y));
\tfloat3 ndc_offset = asfloat(uint3(xe_sys[8].w, xe_sys[9].x, xe_sys[9].y));
\tprecise float3 position = float3(xy, z) * ndc_scale + ndc_offset * w;
\treturn float4(position, w);
}}
'''
# The XenosRecomp body declares its own outputs (oTexCoord*, oColor*) as
# parameters; keep them as locals the body can write and the compiler drops.
for name in re.findall(r'out\s+float4\s+(\w+)\s*:', params):
    if name != 'oPos':
        out = out.replace('\tprecise float4 oPos = 0.0;', f'\tfloat4 {name};\n\tprecise float4 oPos = 0.0;', 1)
open(args.dst, 'w').write(out)
